export const CATEGORY_SEED: CategorySeed[] = (() => {
  const list: CategorySeed[] = [];
  let sort = 0;
  // 25 类排在最前（服装店主营），其余按大类号排序
  const order = [25, 18, 26, 24, 23];
  const sorted = [...RAW].sort((a, b) => order.indexOf(a[0]) - order.indexOf(b[0]));
  for (const [niceClass, groupCode, groupName, names] of sorted) {
    for (const name of names) {
      list.push({ niceClass, groupCode, groupName, name, sort: sort++ });
    }
  }
  return list;
})();
